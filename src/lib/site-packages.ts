import { apiGet } from "@/lib/api/public";
import type { Lang } from "@/components/site/i18n/LanguageProvider";

// Shape exactly as GET /public/plans returns it — the platform-wide catalog,
// full locale maps (no `lang` param on this endpoint, unlike projects), see
// core_backend's internal/api/view.PublicPlan. `price` of 0 means "not yet
// set".
export interface Package {
  id: string;
  slug: string;
  name: { en: string; mn?: string };
  tagline?: { en: string; mn?: string };
  price: number;
  currency: string;
  billing_note?: { en: string; mn?: string };
  features: { en: string[]; mn?: string[] };
  highlighted: boolean;
  sort_order: number;
  is_active: boolean;
  created_at: string;
  updated_at: string;
}

/**
 * GET /public/plans — no credential of any kind. Active only, sorted by sort_order.
 * Returns [] (rather than throwing) if the API is unreachable or errors, so a
 * backend hiccup degrades to the "coming soon" empty state instead of a 500.
 */
export async function listPackages(): Promise<Package[]> {
  try {
    const { data } = await apiGet<Package[]>("/public/plans", { limit: 100 });
    return data.filter((p) => p.is_active).sort((a, b) => a.sort_order - b.sort_order);
  } catch (err) {
    console.error("listPackages failed, showing empty state:", err);
    return [];
  }
}

/** Flattens a Package's locale maps down to plain strings for one language, falling back to `en`. */
export function localizePackage(pkg: Package, lang: Lang) {
  return {
    id: pkg.id,
    slug: pkg.slug,
    name: pkg.name[lang] ?? pkg.name.en,
    tagline: pkg.tagline?.[lang] ?? pkg.tagline?.en,
    price: pkg.price,
    currency: pkg.currency,
    billingNote: pkg.billing_note?.[lang] ?? pkg.billing_note?.en,
    features: pkg.features[lang] ?? pkg.features.en,
    highlighted: pkg.highlighted,
  };
}

/** "₮ —" for an unset price (0), otherwise a formatted "₮ 4,500,000" (or the raw currency code if not MNT). */
export function formatPrice(price: number, currency: string) {
  if (price <= 0) return "₮ —";
  const amount = price.toLocaleString("en-US");
  return currency === "MNT" ? `₮ ${amount}` : `${amount} ${currency}`;
}
